export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let str = TR[lang]?.[key] ?? TR['fr'][key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replace(`{${k}}`, String(v))
  return str
}
